"""``env.example`` and ``docs/settings-reference.md`` must match ``Settings``.

Both files are generated by ``scripts/gen_settings_docs.py``. When this test
fails, run ``uv run python scripts/gen_settings_docs.py`` and commit the result.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[3] / "scripts" / "gen_settings_docs.py"


@pytest.fixture(scope="module")
def generator():  # type: ignore[no-untyped-def]
    spec = importlib.util.spec_from_file_location("gen_settings_docs", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses resolve their module here
    try:
        spec.loader.exec_module(module)
        yield module
    finally:
        sys.modules.pop(spec.name, None)


def test_generated_files_are_up_to_date(generator) -> None:  # type: ignore[no-untyped-def]
    for path, expected in generator.build().items():
        assert path.read_text(encoding="utf-8") == expected, (
            f"{path.name} is stale — run `uv run python scripts/gen_settings_docs.py`"
        )


def test_every_settings_field_is_documented(generator) -> None:  # type: ignore[no-untyped-def]
    from prismal.core.config import Settings

    reference = generator.REFERENCE_MD.read_text(encoding="utf-8")
    env_example = generator.ENV_EXAMPLE.read_text(encoding="utf-8")
    for name in Settings.model_fields:
        env = f"PRISMAL_{name.upper()}"
        assert f"`{env}`" in reference, env
        assert f"{env}=" in env_example, env


def test_secrets_never_carry_a_default(generator) -> None:  # type: ignore[no-untyped-def]
    from prismal.core.config import Settings

    for doc in generator.collect(Settings, "PRISMAL_"):
        if doc.secret:
            assert doc.default == "", doc.env
